'use strict';

const pmScheduleRepository = require('../repositories/pmSchedule.repository');
const notificationService = require('./notification.service');
const auditService = require('./audit.service');
const { prisma } = require('../config/database');

class PMSchedulerService {
  /**
   * Executes due PM schedules and generates Work Orders idempotently.
   * Can be invoked by node-cron or via admin "Run Now" endpoint.
   */
  async runDueSchedules(adminId = null, clientIp = null) {
    const now = new Date();
    console.info(`[PMScheduler] Scanning for due schedules at ${now.toISOString()}...`);

    // 1. Find all active schedules where nextDueDate <= now
    const dueSchedules = await prisma.pMSchedule.findMany({
      where: {
        isActive: true,
        nextDueDate: { lte: now },
      },
      include: {
        asset: { include: { location: true } },
        checklistItems: { orderBy: { order: 'asc' } },
      },
    });

    const generatedWorkOrders = [];
    const skippedDuplicateCount = 0;

    for (const schedule of dueSchedules) {
      // 2. Idempotency Check:
      // Verify whether a PM work order was already created for this schedule today or for this cycle
      const startOfToday = new Date();
      startOfToday.setHours(0, 0, 0, 0);

      const existingWOToday = await prisma.workOrder.findFirst({
        where: {
          pmScheduleId: schedule.id,
          createdAt: { gte: startOfToday },
        },
      });

      if (existingWOToday) {
        console.info(`[PMScheduler] Skipping schedule ${schedule.id} (${schedule.name}) - already generated today.`);
        continue;
      }

      // Format checklist into description or initial note
      const checklistText = schedule.checklistItems.length > 0
        ? '\n\nChecklist Inspection Tasks:\n' +
          schedule.checklistItems.map((item) => `[ ] ${item.order}. ${item.description}`).join('\n')
        : '';

      const fullDescription = `${schedule.description || 'Routine Preventive Maintenance Service.'}${checklistText}`;

      // 3. Atomic Transaction:
      // Create Work Order, record initial status history, update schedule lastGeneratedAt & advance nextDueDate
      const result = await prisma.$transaction(async (tx) => {
        // Calculate next due date: advance by frequencyDays from current nextDueDate
        const currentNextDue = new Date(schedule.nextDueDate);
        const nextTargetDate = new Date(currentNextDue.getTime() + schedule.frequencyDays * 86400000);

        // System fallback admin user if adminId not provided
        let creatorId = adminId;
        if (!creatorId) {
          const sysAdmin = await tx.user.findFirst({ where: { role: 'ADMIN' } });
          creatorId = sysAdmin?.id;
        }

        // Set due date to nextDueDate + 3 days buffer
        const woDueDate = new Date(now.getTime() + 3 * 86400000);

        const wo = await tx.workOrder.create({
          data: {
            title: `[PM] ${schedule.name} - ${schedule.asset?.name || 'Asset'}`,
            description: fullDescription,
            assetId: schedule.assetId,
            priority: 'MEDIUM',
            status: 'OPEN',
            pmScheduleId: schedule.id,
            createdById: creatorId,
            dueDate: woDueDate,
            estimatedCost: 1500,
          },
          include: { asset: true },
        });

        await tx.workOrderStatusHistory.create({
          data: {
            workOrderId: wo.id,
            fromStatus: null,
            toStatus: 'OPEN',
            changedById: creatorId,
            reason: `Automatically generated by PM Scheduler for ${schedule.name}`,
          },
        });

        await tx.pMSchedule.update({
          where: { id: schedule.id },
          data: {
            lastGeneratedAt: now,
            nextDueDate: nextTargetDate,
          },
        });

        return wo;
      });

      generatedWorkOrders.push(result);

      // Notify Admins
      const admins = await prisma.user.findMany({
        where: { role: 'ADMIN', isActive: true },
        select: { id: true },
      });
      for (const a of admins) {
        notificationService.notify({
          userId: a.id,
          type: 'GENERAL',
          title: `PM Work Order Generated`,
          message: `Work Order #${result.id.slice(-6)} was auto-generated for ${schedule.name}.`,
          referenceId: result.id,
          referenceType: 'WORK_ORDER',
          emailUser: false,
        }).catch(() => {});
      }
    }

    if (adminId) {
      await auditService.log({
        userId: adminId,
        action: 'TRIGGER_PM_SCHEDULER',
        entityType: 'PMSchedule',
        entityId: 'SYSTEM',
        details: { generatedCount: generatedWorkOrders.length, scannedCount: dueSchedules.length },
        ipAddress: clientIp,
      });
    }

    console.info(
      `[PMScheduler] Execution complete. Generated ${generatedWorkOrders.length} PM work orders.`
    );

    return {
      scannedSchedules: dueSchedules.length,
      generatedCount: generatedWorkOrders.length,
      workOrders: generatedWorkOrders,
    };
  }
}

module.exports = new PMSchedulerService();
